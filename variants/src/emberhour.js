  const typingIn = e => { const t = e.target; return !!(t && (t.tagName === 'INPUT' || t.tagName === 'TEXTAREA' || t.isContentEditable)); };

  function boot() {
    if (!window.EMBER || !window.THREE) return setTimeout(boot, 250);
    E = window.EMBER; T = window.THREE;
    try { start(); } catch (err) { console.warn('Ember Hour layer failed to start:', err); }
  }

  function start() {
    state = load();
    build();
    // The arches' glows join the base light budget (r115); dark ones take no slot.
    if (E.addLamp) for (const a of arches) E.addLamp(a.userData.glow);
    // The arches' glow lights change the light count; compile for it now (r114).
    if (E.warmShaders) E.warmShaders();
    buildHud();
    addEventListener('keydown', e => {
      if (e.key !== 'h' && e.key !== 'H') return;
      // anyOverlayOpen lives inside the base game's closure, so the old typeof
      // guard was always false and typing an "h" in the strain journal opened
      // the hour (r114 audit). The base exposes it, and a text field is checked.
      if (typingIn(e) || (E.overlayOpen && E.overlayOpen())) return;
      manualUntil = performance.now() / 1000 + MANUAL_HOUR;
    });
    requestAnimationFrame(loop);
  }

  function load() {
    try { const raw = JSON.parse(localStorage.getItem(STORE) || 'null');
      if (raw && Array.isArray(raw.found)) return raw; } catch (_) {}
    return { found: [], hours: 0 };
  }
  function save() { try { localStorage.setItem(STORE, JSON.stringify(state)); } catch (_) {} }

  // --- the arches ---------------------------------------------------------
  function build() {
    const post = new T.BoxGeometry(0.7, 5.2, 0.7);
    const lintel = new T.BoxGeometry(4.6, 0.8, 0.9);
    const veil = new T.PlaneGeometry(3.1, 4.4);
    const cold = new T.MeshStandardMaterial({ color: 0x2b2735, roughness: 1, flatShading: true });

    for (const spec of ARCHES) {
      const g = new T.Group();
      for (const side of [-1, 1]) {
        const p = new T.Mesh(post, cold); p.position.set(side * 1.9, 2.6, 0); g.add(p);
      }
      const top = new T.Mesh(lintel, cold); top.position.y = 5.4; g.add(top);
      const sheet = new T.Mesh(veil, new T.MeshBasicMaterial({
        color: 0xffb45e, transparent: true, opacity: 0, side: T.DoubleSide, depthWrite: false }));
      sheet.position.y = 2.3; g.add(sheet);
      const glow = E.lampLight(0xffb45e, 0, 16); glow.position.y = 3; g.add(glow);
      g.position.set(spec.x, 0, spec.z);
      g.userData = { spec, sheet, glow, phase: Math.random() * 6.28, taken: state.found.includes(spec.id) };
      E.scene.add(g); arches.push(g);
    }
    sealArches();
  }

  // One geometry, twelve instances, one draw call: the arches all stand square
  // to the world, so an instance is a translation and nothing else.
  function sealArches() {
    if (!ARCH_INFILL_GLB || !T.GLTFLoader) return;
    let bytes;
    try { bytes = Uint8Array.from(atob(ARCH_INFILL_GLB), c => c.charCodeAt(0)); }
    catch (err) { console.warn('Ember Hour: the arch stone did not decode', err); return; }
    new T.GLTFLoader().parse(bytes.buffer, '', gltf => {
      let geometry = null;
      gltf.scene.traverse(o => { if (!geometry && o.isMesh) geometry = o.geometry; });
      if (!geometry) return;
      // A shade lighter than the arch itself so the courses read at night; at
      // the posts' own colour the whole opening was one black rectangle.
      const stone = new T.MeshStandardMaterial({ color: 0x413b4e, roughness: 1, flatShading: true });
      seals = new T.InstancedMesh(geometry, stone, arches.length);
      seals.castShadow = false; seals.receiveShadow = true;
      const m = new T.Matrix4();
      arches.forEach((a, i) => { m.makeTranslation(a.position.x, 2.48, a.position.z); seals.setMatrixAt(i, m); });
      seals.instanceMatrix.needsUpdate = true;
      E.scene.add(seals);
    }, err => console.warn('Ember Hour: the arch stone did not parse', err));
  }

  // --- is the hour open ---------------------------------------------------
  function peakActive() {
    const bridge = globalThis.emberwatchPeakSession;
    if (!bridge || !bridge.status) return null;
    try { const s = bridge.status(); return !!(s.connected && (s.active || s.busy)); }
    catch (_) { return null; }
  }

  function loop(now) {
    requestAnimationFrame(loop);
    const t = now / 1000;
    const live = peakActive();
    const manual = t < manualUntil;
    const wasOpen = open;
    open = !!live || manual;

    if (seals) seals.visible = !open;                  // shut means walled up
    if (open && !wasOpen) flash('The hour opens.');
    if (!open && wasOpen) flash('The hour closes.');
    if (open && !wasOpen) { state.hours++; save(); }

    for (const a of arches) {
      const d = a.userData;
      const target = open && !d.taken ? 1 : 0;
      d.sheet.material.opacity += ((open ? (d.taken ? 0.12 : 0.62) : 0) - d.sheet.material.opacity) * 0.05;
      d.glow.intensity += ((open ? (d.taken ? 0.3 : 1.5) : 0) * d.glow.userData.lampScale - d.glow.intensity) * 0.05;
      d.phase += 0.03;
      d.sheet.material.opacity += Math.sin(d.phase) * 0.02 * target;

      if (open && !d.taken) {
        const dist = Math.hypot(E.player.x - a.position.x, E.player.z - a.position.z);
        if (dist < REACH) {
          d.taken = true;
          state.found.push(d.spec.id); save();
          flash(d.spec.says);
        }
      }
    }
    paint(live, manual);
  }

